/// Checks whether a word is in the stopwords set (case-insensitive, zero-alloc when already lowercase).
#[inline]
pub fn is_stopword(word: &str) -> bool {
    if word.bytes().all(|b| !b.is_ascii_uppercase()) {
        STOPWORDS.binary_search(&word).is_ok()
    } else {
        let lower = word.to_ascii_lowercase();
        STOPWORDS.binary_search(&lower.as_str()).is_ok()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_stopwords_sorted() {
        for window in STOPWORDS.windows(2) {
            assert!(
                window[0] < window[1],
                "STOPWORDS not sorted: {:?} >= {:?}",
                window[0],
                window[1]
            );
        }
    }

    #[test]
    fn test_is_stopword_matches() {
        assert!(is_stopword("the"));
        assert!(is_stopword("THE"));
        assert!(is_stopword("The"));
        assert!(is_stopword("anthropic"));
        assert!(is_stopword("OpenAI"));
        assert!(is_stopword("workspace"));
        assert!(!is_stopword("Alice"));
        assert!(!is_stopword("Bob"));
        assert!(!is_stopword("cryptocurrency"));
    }
}
