pub fn md5_bytes(data: &[u8]) -> [u8; 16] {
    let mut a0: u32 = 0x6745_2301;
    let mut b0: u32 = 0xefcd_ab89;
    let mut c0: u32 = 0x98ba_dcfe;
    let mut d0: u32 = 0x1032_5476;

    let bit_len = (data.len() as u64) * 8;
    let mut padded = Vec::with_capacity(data.len() + 72);
    padded.extend_from_slice(data);
    padded.push(0x80);
    while (padded.len() % 64) != 56 {
        padded.push(0);
    }
    padded.extend_from_slice(&bit_len.to_le_bytes());

    for chunk in padded.chunks_exact(64) {
        let mut words = [0u32; 16];
        for (i, word) in words.iter_mut().enumerate() {
            let offset = i * 4;
            *word = u32::from_le_bytes([
                chunk[offset],
                chunk[offset + 1],
                chunk[offset + 2],
                chunk[offset + 3],
            ]);
        }

        let mut state_a = a0;
        let mut state_b = b0;
        let mut state_c = c0;
        let mut state_d = d0;

        for step in 0..64 {
            let (func_out, word_idx) = match step {
                0..16 => ((state_b & state_c) | (!state_b & state_d), step),
                16..32 => (
                    (state_d & state_b) | (!state_d & state_c),
                    (5 * step + 1) % 16,
                ),
                32..48 => (state_b ^ state_c ^ state_d, (3 * step + 5) % 16),
                _ => (state_c ^ (state_b | !state_d), (7 * step) % 16),
            };

            let temp = state_d;
            state_d = state_c;
            state_c = state_b;
            state_b = state_b.wrapping_add(
                state_a
                    .wrapping_add(func_out)
                    .wrapping_add(K[step])
                    .wrapping_add(words[word_idx])
                    .rotate_left(S[step]),
            );
            state_a = temp;
        }

        a0 = a0.wrapping_add(state_a);
        b0 = b0.wrapping_add(state_b);
        c0 = c0.wrapping_add(state_c);
        d0 = d0.wrapping_add(state_d);
    }

    let mut out = [0u8; 16];
    out[0..4].copy_from_slice(&a0.to_le_bytes());
    out[4..8].copy_from_slice(&b0.to_le_bytes());
    out[8..12].copy_from_slice(&c0.to_le_bytes());
    out[12..16].copy_from_slice(&d0.to_le_bytes());
    out
}

pub fn md5_hex(s: impl AsRef<[u8]>) -> String {
    let bytes = md5_bytes(s.as_ref());
    let mut out = String::with_capacity(32);
    for b in bytes {
        use std::fmt::Write;
        let _ = write!(out, "{b:02x}");
    }
    out
}
